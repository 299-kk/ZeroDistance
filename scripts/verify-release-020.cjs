const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto'), assert = require('node:assert/strict'), sharp = require('sharp'), { spawn } = require('node:child_process')
let playwright
try { playwright = require('playwright') } catch { playwright = require(path.join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')) }
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
async function run() {
  const root = path.resolve(__dirname, '..'), output = path.join(root, '.qa/release-020', crypto.randomUUID()), user = path.join(output, 'user'), game = path.join(output, 'game')
  const write = (file, data) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, data) }
  const ids = ['1.20.1-fabric', '1.21.1-forge']
  for (const [index, id] of ids.entries()) {
    write(path.join(game, 'versions', id, id + '.json'), JSON.stringify({ id, _mcVersion: index ? '1.21.1' : '1.20.1', _loader: index ? 'forge' : 'fabric', _loaderVersion: 'fixture', _gameDir: true, _flattenedAt: '2026-10-21T00:00:00Z', mainClass: 'net.minecraft.client.main.Main', libraries: [] }))
    write(path.join(game, 'versions', id, id + '.jar'), Buffer.alloc(4096 * (index + 1)))
  }
  write(path.join(game, 'assets', 'shared-not-an-instance'), Buffer.alloc(10000))
  const account = { id: 'zero-qa-offline', type: 'offline', username: 'ZeroQA', uuid: '12345678123456781234567812345678' }
  write(path.join(user, 'accounts.json'), JSON.stringify({ accounts: [account], selectedId: account.id }))
  write(path.join(user, 'settings.json'), JSON.stringify({ configVersion: 1, gameFolderPolicyVersion: 1, gameDir: game, activeFolder: game, folders: [{ name: 'QA games', path: game, isDefault: true }], theme: 'transparent', autoUpdate: false }))
  const children = Array.from({ length: 3 }, () => spawn(process.execPath, ['-e', 'setInterval(()=>{},1000)'], { stdio: 'ignore', windowsHide: true }))
  write(path.join(user, 'running-game.json'), JSON.stringify(children.map((child, index) => ({ pid: child.pid, versionId: ids[index === 2 ? 1 : 0], folder: game, effectiveGameDir: path.join(game, 'versions', ids[index === 2 ? 1 : 0]), logDir: output, startedAt: new Date().toISOString() }))))
  const catalog = ['26.3', '1.21.11', '1.21.1', '1.20.6', '1.20.1'].map(id => ({ id, type: 'release', url: 'https://piston-meta.mojang.com/fixture', releaseTime: '2026-10-01T00:00:00Z' }))
  for (const version of catalog) write(path.join(user, 'version-size-cache', version.id + '.json'), JSON.stringify({ id: version.id, downloads: { client: { size: 20_000_000 } }, assetIndex: { size: 100_000, totalSize: 120_000_000 }, libraries: [{ name: 'qa:lib:1', downloads: { artifact: { path: 'qa/lib.jar', size: 1_000_000 } } }] }))
  const png = path.join(output, 'skin.png')
  await sharp({ create: { width: 64, height: 64, channels: 4, background: { r: 60, g: 130, b: 180, alpha: 1 } } }).png().toFile(png)
  const env = { ...process.env, ZERO_DISTANCE_DATA_DIR: user, ZERO_DISTANCE_DISCOVERY_ROOTS: '[]' }; delete env.ELECTRON_RUN_AS_NODE
  const executablePath = process.env.ZERO_DISTANCE_EXECUTABLE || require('electron')
  const args = [...(process.env.ZERO_DISTANCE_EXECUTABLE ? ['--user-data-dir=' + user, '--no-auto-discovery'] : [root]), '--disable-features=CalculateNativeWinOcclusion', '--disable-renderer-backgrounding']
  const app = await playwright._electron.launch({ executablePath, args, cwd: root, env, timeout: 60000 })
  const report = { ok: false, packaged: !!process.env.ZERO_DISTANCE_EXECUTABLE, output, passed: [], errors: [] }
  try {
    await require('./electron-consent.cjs')(app)
    let page
    for (let n = 0; n < 200; n++) { page = app.windows().find(p => p.url().includes('/index.html')); if (page) break; await delay(100) }
    assert(page); page.on('pageerror', error => report.errors.push(error.message))
    await page.locator('.zd-instance').first().waitFor({ timeout: 30000 })
    await page.waitForFunction(() => document.querySelector('.zd-session-strip')?.textContent.includes('已启动 2 个游戏版本'))
    assert((await page.locator('.zd-session-strip').innerText()).includes('3 个游戏进程'))
    assert.equal(await page.locator('.sidebar').evaluate(el => Math.round(el.getBoundingClientRect().width)), 132)
    await page.screenshot({ path: path.join(output, '01-home.png') })
    report.passed.push('Restores three live test processes as two running game versions, with a compact navigation rail')
    children.forEach(child => child.kill())
    await page.waitForFunction(() => document.querySelector('.zd-session-strip')?.textContent.includes('当前没有运行中的游戏'), { timeout: 15000 })
    report.passed.push('Running counts clear after the tracked processes exit')
    await app.evaluate(({ shell }) => { globalThis.__qaOpened = []; shell.openPath = async file => { globalThis.__qaOpened.push(file); return '' } })
    await page.getByRole('button', { name: '打开游戏目录', exact: true }).click()
    assert.deepEqual(await app.evaluate(() => globalThis.__qaOpened), [game])
    const size = await page.evaluate(({ id, folder }) => window.kamucl.invoke('versions:size', id, folder), { id: ids[0], folder: game })
    assert(size.bytes >= 4096 && size.bytes < 10000); assert.equal(size.partial, false)
    assert.equal(await page.evaluate(() => window.kamucl.invoke('versions:size', '..', 'C:\\').then(() => false, () => true)), true)
    report.passed.push('Home opens the registered folder; real instance byte counts exclude shared assets and reject unknown roots')
    await page.locator('.zd-instance-select').filter({ hasText: ids[0] }).click()
    await page.locator('[data-nav="resources"]').click(); await page.locator('[data-nav="skins"]').click()
    await page.locator('input[type="file"]').setInputFiles(png)
    await page.getByRole('button', { name: '保存皮肤', exact: true }).click()
    await page.locator('.pane-preview canvas').waitFor()
    await page.getByRole('group', { name: '离线皮肤模型' }).getByRole('button', { name: '纤细 · 窄手臂' }).click()
    await page.waitForFunction(async () => (await window.kamucl.invoke('skin:profile')).skins[0]?.variant === 'slim')
    await page.getByRole('button', { name: '应用到所选游戏' }).click()
    const extra = path.join(game, 'versions', ids[0], 'CustomSkinLoader/ExtraList/ZeroDistanceLocal.json')
    for (let n = 0; n < 50 && !fs.existsSync(extra); n++) await delay(100)
    assert.equal(JSON.parse(fs.readFileSync(extra)).model, 'slim')
    await page.screenshot({ path: path.join(output, '02-offline-skin.png') })
    await page.reload(); await page.locator('.zd-hero').waitFor()
    await page.locator('.zd-instance-select').filter({ hasText: ids[0] }).click()
    if (await page.locator('[data-nav="resources"]').getAttribute('aria-expanded') !== 'true') await page.locator('[data-nav="resources"]').click()
    await page.locator('[data-nav="skins"]').click()
    assert.equal(await page.getByRole('button', { name: '纤细 · 窄手臂' }).getAttribute('aria-pressed'), 'true')
    report.passed.push('Offline PNG and slim model survive reload; application creates a matching CSL configuration in the selected instance')
    await app.evaluate(({ ipcMain }, catalog) => {
      const stub = (channel, fn) => { ipcMain.removeHandler(channel); ipcMain.handle(channel, fn) }
      stub('versions:catalog', () => ({ versions: catalog, checkedAt: Date.now(), stale: false }))
      stub('versions:manifest', () => catalog)
      globalThis.__qaFiles = []; globalThis.__qaCommitted = 0
      stub('community:search', () => ({ items: [{ source: 'modrinth', projectId: 'qa-resource', title: 'QA resource', kind: 'mod', description: 'Offline test fixture', downloads: 1, updatedAt: '2026-10-21' }], total: 1, offset: 0, limit: 20 }))
      stub('community:files', (_event, source, id, filter) => {
        globalThis.__qaFiles.push({ source, id, filter })
        return [{ source: 'modrinth', projectId: id, fileId: 'qa-file', fileName: 'resource-fixture.jar', version: '1.0', size: 153600, releaseType: 'release', url: 'https://cdn.modrinth.com/fixture.jar', gameVersions: ['1.20.1'], loaders: ['fabric'], date: '2026-10-21' }]
      })
      stub('mods:prepare', (_event, target) => new Promise(resolve => { globalThis.__qaResolve = () => resolve({ id: 'qa-plan', target: { ...target, mcVersion: '1.20.1', loader: 'fabric' }, files: [{ fileName: 'lan-fixture.jar', name: 'LAN', version: '1', dependency: false }, { fileName: 'api.jar', name: 'API', version: '1', dependency: true }], missing: [], warnings: [] }) }))
      stub('mods:commit', () => { globalThis.__qaCommitted++; return 'QA installed' })
      stub('mods:discard', () => {})
    }, catalog)
    await page.locator('[data-nav="friends"]').click()
    await page.getByRole('dialog', { name: '请先确认主机的验证设置' }).waitFor()
    await page.getByLabel('不再提示', { exact: true }).check()
    await page.getByRole('button', { name: '我知道了', exact: true }).click()
    await page.locator('[data-nav="community"]').click()
    await page.getByRole('button', { name: '版本与大小', exact: true }).click()
    const requested = await app.evaluate(() => globalThis.__qaFiles[0])
    assert.equal(requested.id, 'qa-resource'); assert.equal(requested.filter.mcVersion, '1.20.1'); assert.equal(requested.filter.loader, 'fabric')
    await page.locator('.resource-download-size').waitFor()
    assert((await page.locator('.resource-download-size').innerText()).includes('150.0 KB'))
    await page.screenshot({ path: path.join(output, '03-compatible-resource.png') })
    await page.getByRole('button', { name: '确认下载', exact: true }).click()
    await page.locator('.modinstall-background').waitFor()
    await page.locator('[data-nav="home"]').click()
    assert.equal(await page.locator('.modinstall-background').count(), 1)
    assert.equal(await page.locator('.modinstall-modal').count(), 0)
    await page.locator('.modinstall-background').click()
    await page.getByRole('button', { name: '最小化前置任务' }).click()
    await app.evaluate(() => globalThis.__qaResolve())
    await page.waitForFunction(() => document.querySelector('.modinstall-background')?.textContent.includes('前置已就绪'))
    assert.equal(await app.evaluate(() => globalThis.__qaCommitted), 0)
    await page.locator('.modinstall-background').click()
    await page.getByRole('button', { name: '一键下载前置并安装' }).click()
    await page.waitForFunction(() => !document.querySelector('.modinstall-background') && !document.querySelector('.modinstall-modal'))
    assert.equal(await app.evaluate(() => globalThis.__qaCommitted), 1)
    report.passed.push('Offline notice persists dismissal; resource file requests carry the selected MC and loader filters')
    report.passed.push('Resource size is prominent; dependency check survives navigation, minimizes/restores, and waits for explicit installation confirmation')
    await page.locator('[data-nav="friends"]').click(); await page.locator('.pick-list').waitFor()
    assert.equal(await page.locator('.offline-connect-notice').count(), 0)
    await page.locator('[data-nav="game"]').click(); await page.locator('[data-tab="download"]').click()
    await page.locator('.version-family').first().waitFor()
    assert.equal(await page.locator('.version-family').count(), 3)
    const group = page.locator('.version-family').filter({ hasText: '1.20.6' })
    await group.locator('summary').click()
    await group.locator('.version-size').first().waitFor()
    await page.waitForFunction(() => [...document.querySelectorAll('.version-family .version-size')].some(el => el.textContent.includes('134.6 MB')))
    assert.equal(await page.evaluate(() => window.kamucl.invoke('versions:downloadSize', '1.20.1').then(x => x.bytes)), 141100000)
    assert.equal(fs.existsSync(path.join(game, 'versions/1.20.1')), false)
    await page.screenshot({ path: path.join(output, '04-version-groups.png') })
    report.passed.push('Download families collapse patch versions; estimates include client/libraries/assets without creating phantom installed versions')
    await page.locator('[data-nav="home"]').click()
    const capture = async () => sharp(await page.screenshot()).raw().toBuffer({ resolveWithObject: true })
    const before = await capture()
    await page.evaluate(() => window.kamucl.invoke('settings:set', { background: { mode: 'color', color: '#e40077', opacity: 1 } }))
    await page.reload(); await page.locator('.shell.has-bg').waitFor()
    await delay(500)
    const after = await capture()
    const offset = (70 * after.info.width + 125) * after.info.channels
    const difference = [0, 1, 2].reduce((sum, channel) => sum + Math.abs(after.data[offset + channel] - before.data[offset + channel]), 0)
    assert(difference > 40, 'Application background must visibly change actual pixels')
    await page.screenshot({ path: path.join(output, '05-background-visible.png') })
    await page.evaluate(() => window.kamucl.invoke('settings:set', { background: { mode: 'none' }, theme: 'blue-white' }))
    await page.reload(); await page.locator('.zd-hero').waitFor()
    await page.screenshot({ path: path.join(output, '06-daylight.png') })
    await page.getByTitle('更新日志', { exact: true }).click()
    assert.equal(await page.locator('.note-version.latest .release-title').count(), 1)
    await delay(600)
    assert.equal(await page.locator('.notes-panel').evaluate(el => getComputedStyle(el).opacity), '1')
    await page.screenshot({ path: path.join(output, '07-release-notes.png') })
    report.passed.push('Background persists and changes rendered pixels; daylight theme and release timeline render correctly')
    assert.deepEqual(report.errors, []); report.ok = true
  } finally {
    children.forEach(child => { if (!child.killed) child.kill() })
    await app.close()
    fs.writeFileSync(path.join(root, '.qa/release-result-020.json'), JSON.stringify(report, null, 2))
  }
  console.log(JSON.stringify(report, null, 2))
}
run().catch(error => { console.error(error); process.exitCode = 1 })
